import net.runelite.cache.ConfigType;
import net.runelite.cache.IndexType;
import net.runelite.cache.definitions.ItemDefinition;
import net.runelite.cache.definitions.ModelDefinition;
import net.runelite.cache.definitions.loaders.ItemLoader;
import net.runelite.cache.definitions.loaders.ModelLoader;
import net.runelite.cache.fs.*;
import net.runelite.cache.index.FileData;

import java.io.File;
import java.io.PrintWriter;
import java.nio.file.Files;
import java.util.*;

// Wilderness Forge "Matte Obsidian & Blood Crimson" re-skin (2026-10-16), read-only on the cache.
// Same colour walk as GenThemeRecolors (every model of the SOURCE item, resolved through the source's
// own recolour table), but each effective colour becomes one of:
//   - untouched: pure black, skin tones, and "keep" colours;
//   - accent (sat >= accentSat OR lum >= accentLum): its faces get the theme's animated lava texture
//     (blade edges, trims, gems) and the colour is recoloured to a crimson fallback;
//   - everything else: matte obsidian, lum' = clamp(round(lum * pMul + pAdd), 2, 126) at hue 0 sat 1.
// Spec lines:
//   theme <name> <texId> <accentSat> <accentLum> [pMul pAdd]
//   theme <name> <texId> auto <fraction> [pMul pAdd]   ranks the item's colours by sat*20 + lum and makes the
//        top ones accents until they cover <fraction> of the inventory model's opaque faces (a colour that would push past fraction + 0.30 is skipped)
//   item <srcId> <newId> <placeholderId> <tradeable> <ops> <theme> <name...>
//   keep <newId> <hsl>[,<hsl>...]
// Writes <out>/variants.txt (CreateItemVariants -replace spec: variant + recolor + models lines) and
// <out>/texmodels.txt (TextureModelFaces spec). Textured model copies get fresh ids from <firstModelId>
// upwards, skipping ids already in the cache; one copy per (source model, texture) is shared by items.
// Prints, per item, the share of opaque faces that end up textured (aim for roughly 10-40%).
// Usage: <cachePath> <specFile> <outDir> <firstModelId>
public class GenForgeObsidian {
    record Theme(int tex, int accentSat, int accentLum, double fraction, double pMul, int pAdd) {
        boolean auto() { return fraction > 0; }
    }

    static final int OBSIDIAN_HUE = 0, OBSIDIAN_SAT = 1;
    static final int CRIMSON_HUE = 0, CRIMSON_SAT = 7;

    public static void main(String[] args) throws Exception {
        Map<String, Theme> themes = new HashMap<>();
        List<String[]> items = new ArrayList<>();
        Map<Integer, Set<Integer>> keep = new HashMap<>();
        for (String l : Files.readAllLines(new File(args[1]).toPath())) {
            l = l.trim();
            if (l.isEmpty() || l.startsWith("#")) continue;
            String[] p = l.split("\\s+");
            switch (p[0]) {
                case "theme" -> {
                    boolean auto = p[3].equals("auto");
                    themes.put(p[1], new Theme(i(p[2]), auto ? 0 : i(p[3]), auto ? 0 : i(p[4]),
                            auto ? Double.parseDouble(p[4]) : 0, p.length > 5 ? Double.parseDouble(p[5]) : 0.22,
                            p.length > 6 ? i(p[6]) : 4));
                }
                case "keep" -> {
                    Set<Integer> s = keep.computeIfAbsent(i(p[1]), k -> new HashSet<>());
                    for (String c : p[2].split(",")) s.add(i(c) & 0xFFFF);
                }
                case "item" -> items.add(l.split("\\s+", 8));
                default -> throw new IllegalArgumentException("bad line: " + l);
            }
        }
        File out = new File(args[2]);
        out.mkdirs();
        int nextModel = i(args[3]);

        try (Store store = new Store(new File(args[0]));
             PrintWriter variants = new PrintWriter(new File(out, "variants.txt"));
             PrintWriter texmodels = new PrintWriter(new File(out, "texmodels.txt"))) {
            store.load();
            Storage storage = store.getStorage();
            Archive archive = store.getIndex(IndexType.CONFIGS).getArchive(ConfigType.ITEM.getId());
            byte[] dec = archive.decompress(storage.loadArchive(archive));
            FileData[] fd = archive.getFileData();
            List<byte[]> contents = SpliceItemOption.splitChunks(dec, fd.length);
            Index models = store.getIndex(IndexType.MODELS);
            Set<Integer> usedModels = new HashSet<>();
            for (Archive a : models.getArchives()) usedModels.add(a.getArchiveId());

            Map<String, Integer> copies = new HashMap<>(); // "srcModel:tex" -> new model id
            Map<String, String> copyColours = new HashMap<>(); // same key -> colour list, must match on reuse
            variants.println("# Generated by GenForgeObsidian from " + args[1] + " -- regenerate rather than hand-edit.");
            texmodels.println("# Generated by GenForgeObsidian from " + args[1]);
            for (String[] p : items) {
                int src = i(p[1]), id = i(p[2]);
                ItemDefinition def = null;
                for (int k = 0; k < fd.length; k++) if (fd[k].getId() == src) def = new ItemLoader().load(src, contents.get(k));
                if (def == null) throw new IllegalStateException("item " + src + " not found");
                Theme t = themes.get(p[6]);
                if (t == null) throw new IllegalStateException("unknown theme " + p[6]);
                Set<Integer> kept = keep.getOrDefault(id, Set.of());

                Map<Integer, Integer> srcRecolor = new HashMap<>();
                if (def.colorFind != null)
                    for (int k = 0; k < def.colorFind.length; k++) srcRecolor.put(def.colorFind[k] & 0xFFFF, def.colorReplace[k] & 0xFFFF);

                TreeSet<Integer> raw = new TreeSet<>(srcRecolor.keySet());
                LinkedHashMap<Integer, ModelDefinition> mdl = new LinkedHashMap<>();
                for (int m : new int[]{def.inventoryModel, def.maleModel0, def.maleModel1, def.maleModel2,
                        def.femaleModel0, def.femaleModel1, def.femaleModel2}) {
                    if (m <= 0 || mdl.containsKey(m)) continue;
                    Archive ma = models.getArchive(m);
                    if (ma == null) throw new IllegalStateException("model " + m + " missing");
                    ModelDefinition md = new ModelLoader().load(m, ma.decompress(storage.loadArchive(ma)));
                    mdl.put(m, md);
                    if (md.faceColors != null) for (short c : md.faceColors) raw.add(c & 0xFFFF);
                }

                Set<Integer> autoAccent = t.auto() ? pickAuto(def, mdl, srcRecolor, kept, t.fraction) : Set.of();
                // classify every raw colour by its effective (source-recoloured) colour
                Set<Integer> accentRaw = new HashSet<>();
                StringBuilder pairs = new StringBuilder();
                int recoloured = 0;
                for (int c : raw) {
                    int eff = srcRecolor.getOrDefault(c, c);
                    int kind = kept.contains(eff) ? 0 : kind(eff, t);
                    if (t.auto() && kind != 0) kind = autoAccent.contains(eff) ? 2 : 1;
                    int nc;
                    if (kind == 0) {
                        if (eff == c) continue;
                        nc = eff; // keep the source's own recolour
                    } else {
                        int l = eff & 127;
                        if (kind == 2) {
                            accentRaw.add(c);
                            nc = CRIMSON_HUE << 10 | CRIMSON_SAT << 7 | clamp((int) Math.round(l * 0.6 + 10));
                        } else {
                            nc = OBSIDIAN_HUE << 10 | OBSIDIAN_SAT << 7 | clamp((int) Math.round(l * t.pMul + t.pAdd));
                        }
                    }
                    if (nc == c) continue;
                    if (pairs.length() > 0) pairs.append(',');
                    pairs.append(c).append(':').append(nc);
                    recoloured++;
                }
                if (recoloured > 255) throw new IllegalStateException(src + ": too many recolours " + recoloured);

                // textured copies of every model that has accent faces
                StringBuilder remap = new StringBuilder();
                int opaque = 0, textured = 0;
                for (var e : mdl.entrySet()) {
                    ModelDefinition md = e.getValue();
                    if (md.faceColors == null) continue;
                    TreeSet<Integer> here = new TreeSet<>();
                    for (int f = 0; f < md.faceCount; f++) {
                        int c = md.faceColors[f] & 0xFFFF;
                        boolean op = md.faceTransparencies == null || (md.faceTransparencies[f] & 0xFF) < 128;
                        if (e.getKey() == def.inventoryModel && op) {
                            opaque++;
                            if (accentRaw.contains(c)) textured++;
                        }
                        if (accentRaw.contains(c)) here.add(c);
                    }
                    if (here.isEmpty()) continue;
                    String colours = here.toString().replaceAll("[\\[\\] ]", "");
                    String key = e.getKey() + ":" + t.tex;
                    Integer copy = copies.get(key);
                    if (copy != null && !copyColours.get(key).equals(colours)) {
                        key = key + ":" + colours; // same model, different accent set: separate copy
                        copy = copies.get(key);
                    }
                    if (copy == null) {
                        while (usedModels.contains(nextModel)) nextModel++;
                        if (nextModel > 65535) throw new IllegalStateException("ran out of model ids under 65536");
                        copy = nextModel++;
                        usedModels.add(copy);
                        copies.put(key, copy);
                        copyColours.put(key, colours);
                        texmodels.println("model " + e.getKey() + " " + copy + " " + t.tex + " " + colours);
                    }
                    if (remap.length() > 0) remap.append(',');
                    remap.append(e.getKey()).append(':').append(copy);
                }

                variants.println("variant " + src + " " + id + " " + p[3] + " " + p[4] + " " + p[5] + " " + p[7]);
                if (pairs.length() > 0) variants.println("recolor " + id + " " + pairs);
                if (remap.length() > 0) variants.println("models " + id + " " + remap);
                System.out.printf("%d -> %d %-34s tex=%d colours=%d accent=%d textured(inv)=%d%%%n", src, id, p[7], t.tex,
                        raw.size(), accentRaw.size(), opaque == 0 ? 0 : textured * 100 / opaque);
            }
            System.out.println("models used up to " + (nextModel - 1) + ", textured copies=" + copies.size());
        }
    }

    /** Effective colours to texture: highest sat*20+lum first, until they cover the wanted share of faces. */
    static Set<Integer> pickAuto(ItemDefinition def, Map<Integer, ModelDefinition> mdl, Map<Integer, Integer> srcRecolor,
                                 Set<Integer> kept, double fraction) {
        ModelDefinition inv = mdl.get(def.inventoryModel);
        Map<Integer, Integer> faces = new HashMap<>();
        int total = 0;
        for (int f = 0; f < inv.faceCount; f++) {
            if (inv.faceTransparencies != null && (inv.faceTransparencies[f] & 0xFF) >= 128) continue;
            int eff = srcRecolor.getOrDefault(inv.faceColors[f] & 0xFFFF, inv.faceColors[f] & 0xFFFF);
            total++;
            if (kept.contains(eff) || kind(eff, new Theme(0, 99, 999, 0, 0, 0)) == 0) continue;
            faces.merge(eff, 1, Integer::sum);
        }
        List<Integer> ranked = new ArrayList<>(faces.keySet());
        ranked.sort(Comparator.comparingInt((Integer c) -> ((c >> 7) & 7) * 20 + (c & 127)).reversed());
        Set<Integer> picked = new HashSet<>();
        int covered = 0;
        for (int c : ranked) {
            if (!picked.isEmpty() && covered >= fraction * total) break;
            if (covered + faces.get(c) > (fraction + 0.30) * total) continue; // a colour that IS the body stays obsidian
            picked.add(c);
            covered += faces.get(c);
        }
        return picked;
    }

    /** 0 = leave alone, 1 = obsidian, 2 = lava accent. */
    static int kind(int hsl, Theme t) {
        int h = (hsl >> 10) & 63, s = (hsl >> 7) & 7, l = hsl & 127;
        if (hsl == 0) return 0;
        if (h >= 3 && h <= 5 && s >= 2 && s <= 4 && l >= 55 && l <= 95) return 0; // skin
        return s >= t.accentSat || l >= t.accentLum ? 2 : 1;
    }

    static int clamp(int l) {
        return Math.max(2, Math.min(126, l));
    }

    static int i(String s) { return Integer.parseInt(s); }
}
