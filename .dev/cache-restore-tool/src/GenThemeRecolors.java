import net.runelite.cache.ConfigType;
import net.runelite.cache.IndexType;
import net.runelite.cache.definitions.ItemDefinition;
import net.runelite.cache.definitions.ModelDefinition;
import net.runelite.cache.definitions.loaders.ItemLoader;
import net.runelite.cache.definitions.loaders.ModelLoader;
import net.runelite.cache.fs.*;
import net.runelite.cache.index.FileData;

import java.io.File;
import java.io.PrintWriter;
import java.nio.file.Files;
import java.util.*;

// Generates themed recolour tables for item variants (read-only on the cache). For every item it
// collects the raw face colours of ALL its models (inventory, male 0-2, female 0-2), resolves each
// through the source item's own recolour table (the new table replaces it), then maps the
// effective colour through a theme:
//   - pure black (0) and skin tones (hue 3-5, sat 2-4, lum 55-95) are left alone;
//   - "accent" colours (sat >= accentSat OR lum >= accentLum) -> accent hue/sat;
//   - everything else -> primary hue/sat;
//   - lum' = clamp(round(lum * mul + add), 2, 126), with separate mul/add for primary and accent.
// Spec lines:
//   theme <name> <pHue> <pSat> <pMul> <pAdd> <aHue> <aSat> <aMul> <aAdd> <accentSat> <accentLum>
//   item <srcId> <newId> <placeholderId> <tradeable> <ops> <theme> <name...>
//   keep <newId> <hsl>[,<hsl>...]   effective colours of that item to leave untouched (e.g. a poison tip)
// Writes <out>/variants.txt (CreateItemVariants spec) and <out>/preview_<newId>.txt
// (PreviewRecolorSet spec) for each item.
// Usage: <cachePath> <specFile> <outDir>
public class GenThemeRecolors {
    record Theme(int pHue, int pSat, double pMul, int pAdd, int aHue, int aSat, double aMul, int aAdd, int accentSat, int accentLum) {}

    public static void main(String[] args) throws Exception {
        Map<String, Theme> themes = new HashMap<>();
        List<String[]> items = new ArrayList<>();
        Map<Integer, Set<Integer>> keep = new HashMap<>();
        for (String l : Files.readAllLines(new File(args[1]).toPath())) {
            l = l.trim();
            if (l.isEmpty() || l.startsWith("#")) continue;
            String[] p = l.split("\\s+");
            if (p[0].equals("theme")) {
                themes.put(p[1], new Theme(i(p[2]), i(p[3]), Double.parseDouble(p[4]), i(p[5]), i(p[6]), i(p[7]),
                        Double.parseDouble(p[8]), i(p[9]), i(p[10]), i(p[11])));
            } else if (p[0].equals("keep")) {
                Set<Integer> s = keep.computeIfAbsent(i(p[1]), k -> new HashSet<>());
                for (String c : p[2].split(",")) s.add(i(c) & 0xFFFF);
            } else if (p[0].equals("item")) {
                items.add(l.split("\\s+", 8));
            }
        }
        File out = new File(args[2]);
        out.mkdirs();

        try (Store store = new Store(new File(args[0])); PrintWriter variants = new PrintWriter(new File(out, "variants.txt"))) {
            store.load();
            Storage storage = store.getStorage();
            Archive archive = store.getIndex(IndexType.CONFIGS).getArchive(ConfigType.ITEM.getId());
            byte[] dec = archive.decompress(storage.loadArchive(archive));
            FileData[] fd = archive.getFileData();
            List<byte[]> contents = SpliceItemOption.splitChunks(dec, fd.length);
            Index models = store.getIndex(IndexType.MODELS);

            variants.println("# Generated by GenThemeRecolors from " + args[1]);
            for (String[] p : items) {
                int src = i(p[1]);
                ItemDefinition def = null;
                for (int k = 0; k < fd.length; k++) if (fd[k].getId() == src) def = new ItemLoader().load(src, contents.get(k));
                if (def == null) throw new IllegalStateException("item " + src + " not found");
                Theme t = themes.get(p[6]);
                if (t == null) throw new IllegalStateException("unknown theme " + p[6]);

                Map<Integer, Integer> srcRecolor = new HashMap<>();
                if (def.colorFind != null)
                    for (int k = 0; k < def.colorFind.length; k++) srcRecolor.put(def.colorFind[k] & 0xFFFF, def.colorReplace[k] & 0xFFFF);

                TreeSet<Integer> raw = new TreeSet<>();
                for (int m : new int[]{def.inventoryModel, def.maleModel0, def.maleModel1, def.maleModel2,
                        def.femaleModel0, def.femaleModel1, def.femaleModel2}) {
                    if (m <= 0) continue;
                    Archive ma = models.getArchive(m);
                    if (ma == null) throw new IllegalStateException("model " + m + " missing");
                    ModelDefinition md = new ModelLoader().load(m, ma.decompress(storage.loadArchive(ma)));
                    if (md.faceColors != null) for (short c : md.faceColors) raw.add(c & 0xFFFF);
                }
                // A source recolour can target a colour that only exists after another mapping; keep its
                // find colours too so nothing it touched is left out.
                raw.addAll(srcRecolor.keySet());

                StringBuilder pairs = new StringBuilder();
                int n = 0, kept = 0;
                for (int c : raw) {
                    int eff = srcRecolor.getOrDefault(c, c);
                    int nc = keep.getOrDefault(i(p[2]), Set.of()).contains(eff) ? -1 : map(eff, t);
                    if (nc < 0) {
                        if (eff != c) { nc = eff; } else { kept++; continue; }
                    }
                    if (nc == c) continue;
                    if (pairs.length() > 0) pairs.append(',');
                    pairs.append(c).append(':').append(nc);
                    n++;
                }
                if (n > 255) throw new IllegalStateException(src + ": too many recolours " + n);
                variants.println("variant " + src + " " + p[2] + " " + p[3] + " " + p[4] + " " + p[5] + " " + p[7]);
                variants.println("recolor " + p[2] + " " + pairs);
                try (PrintWriter pv = new PrintWriter(new File(out, "preview_" + p[2] + ".txt"))) {
                    pv.println("recolor " + pairs.toString().replace(':', ','));
                    pv.println("item " + src + " " + p[2] + " " + p[3] + " " + p[7]);
                }
                System.out.printf("%d -> %d %-40s colours=%d recoloured=%d keptSkin/black=%d%n", src, i(p[2]), p[7], raw.size(), n, kept);
            }
        }
    }

    /** Returns the themed colour, or -1 to leave the colour as is. */
    static int map(int hsl, Theme t) {
        int h = (hsl >> 10) & 63, s = (hsl >> 7) & 7, l = hsl & 127;
        if (hsl == 0) return -1;
        if (h >= 3 && h <= 5 && s >= 2 && s <= 4 && l >= 55 && l <= 95) return -1; // skin
        boolean accent = s >= t.accentSat || l >= t.accentLum;
        int nh = accent ? t.aHue : t.pHue, ns = accent ? t.aSat : t.pSat;
        double mul = accent ? t.aMul : t.pMul;
        int add = accent ? t.aAdd : t.pAdd;
        int nl = (int) Math.round(l * mul + add);
        nl = Math.max(2, Math.min(126, nl));
        return nh << 10 | ns << 7 | nl;
    }

    static int i(String s) { return Integer.parseInt(s); }
}
